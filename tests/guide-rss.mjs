import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {feedItem,generateRSS} from '../scripts/generate-rss.mjs';
const root=path.resolve(import.meta.dirname,'..');
const fixture='<title>A &amp; B</title><main><h1>전체 안내</h1><p>끝까지 포함된 내용 ]]></p><a href="/about/" onclick="unsafe()">소개</a><script>unsafe()</script></main>';
const item=feedItem(fixture,'https://balzaguk.com/guides/example/');
assert.ok(item.includes('끝까지 포함된 내용'));
assert.ok(item.includes('https://balzaguk.com/about/'));
assert.ok(item.includes('A &amp; B'));
assert.ok(item.includes(']]]]><![CDATA[>'));
assert.ok(!item.includes('unsafe()'));
assert.throws(()=>feedItem(fixture,'https://other.example/'));
assert.throws(()=>feedItem('<meta name="robots" content="noindex,follow">'+fixture,'https://balzaguk.com/hidden/'));
const before=await readFile(path.join(root,'rss.xml'),'utf8');
assert.ok(Buffer.byteLength(before)<10*1024*1024);
assert.equal((before.match(/<item>/g)||[]).length,22);
assert.ok(before.includes('https://balzaguk.com/with-dog/daejeon/'));
assert.ok(!before.includes('<pubDate>'));
assert.equal((await generateRSS(root)).changed,false);
assert.equal(await readFile(path.join(root,'rss.xml'),'utf8'),before);
console.log('PASS: full public content, absolute links, XML/CDATA escaping, unsafe markup exclusion, no fabricated publication dates and stable unchanged feed.');
